"""
What my test runs. ← UNIT 8, MILESTONE 3

One scenario per criterion in criteria.md, in the same order. `run_eval.py`
runs everything here three times against the live service.

The texts are the fixed evaluation files from unit 7, chosen before anything
was scored and never used for calibration:

    eval_data/human_samples.json   20 Project Gutenberg passages (pre-1930),
                                   8 of them deliberately plain writing
    eval_data/ai_samples.json      10 passages generated by Claude

Criterion 1 is about false positives, and the template says to use my own
writing for it. My criterion 1 (written in unit 7) names the 20-passage
known-human set instead, so that is what runs here: a criterion is tested
against what it says, not against what the template assumed.

A scenario carries **either** of these:

    "texts"   a list of strings. Each is sent as {"text": ..., "creator_id": ...}
              with a creator_id made up for you.

    "bodies"  a list of whole request bodies, sent exactly as written. A body
              of the form {"_raw": "...", "_content_type": "..."} is sent as
              those raw bytes with that Content-Type instead of as JSON — the
              only way to send a body that isn't JSON at all.

Optional keys (handled by run_eval.py):

    "appeal"           after each submission, POST /appeal against the
                       content_id that came back, then check the audit log
    "unknown_appeals"  also appeal this many made-up content_ids
    "check"            fn(results_by_scenario_name) -> (cell_text, passed)
                       for one trial; fills the Run columns and the Verdict
"""

import json
import statistics
from pathlib import Path

_DATA = Path(__file__).parent / "eval_data"
_HUMAN = json.loads((_DATA / "human_samples.json").read_text(encoding="utf-8"))
_AI = json.loads((_DATA / "ai_samples.json").read_text(encoding="utf-8"))

HUMAN_TEXTS = [s["text"] for s in _HUMAN]
AI_TEXTS = [s["text"] for s in _AI]
_OK_TEXT = AI_TEXTS[0]

# Targets, verbatim from criteria.md (committed in unit 7, before any results).
MAX_FALSE_POSITIVES = 1
MIN_GAP = 0.20


def _scored(results):
    return [r for r in results if r.get("status") == 200]


def check_false_positives(by_name):
    rows = by_name["1. known-human set"]
    flagged = sum(r.get("guess") == "ai" for r in rows)
    ok = len(_scored(rows)) == len(HUMAN_TEXTS) and flagged <= MAX_FALSE_POSITIVES
    return f"{flagged}/{len(rows)} labelled AI", ok


def check_gap(by_name):
    human = _scored(by_name["1. known-human set"])
    ai = _scored(by_name["2. known-AI set"])
    if len(human) != len(HUMAN_TEXTS) or len(ai) != len(AI_TEXTS):
        return "incomplete", False
    gap = statistics.mean(r["confidence"] for r in ai) - statistics.mean(r["confidence"] for r in human)
    return f"gap {gap:.3f}", gap >= MIN_GAP


def check_labels(by_name):
    import scoring
    import config

    # (a) the sweep: every score in [0, 1] gets one label, changing only at the thresholds
    changes, previous = [], None
    for i in range(10_001):
        guess, _ = scoring.score_to_label(i / 10_000)
        if previous is not None and guess != previous:
            changes.append(i / 10_000)
        previous = guess
    sweep_ok = changes == [config.HUMAN_THRESHOLD, round(config.AI_THRESHOLD + 1e-4, 4)]
    # (b) the live 30
    seen = {r.get("guess") for r in _scored(by_name["3. label coverage (all 30)"])}
    labels_ok = seen >= {"human", "unsure", "ai"}
    return (f"{len(seen & {'human', 'unsure', 'ai'})}/3 labels, sweep {'ok' if sweep_ok else 'GAP'}",
            sweep_ok and labels_ok)


def check_appeals(by_name):
    rows = by_name["4. appeal path"]
    valid = [r for r in rows if not r.get("unknown")]
    unknown = [r for r in rows if r.get("unknown")]
    valid_ok = sum(r.get("appeal_status") == 200 and r.get("appeal_returned_status") == "under_review"
                   and r.get("appeal_entries") == 1 and r.get("reason_logged") for r in valid)
    unknown_ok = sum(r.get("appeal_status") == 404 and r.get("appeal_entries") == 0 for r in unknown)
    return f"{valid_ok}/5 + {unknown_ok}/3 -> 404", valid_ok == 5 and unknown_ok == 3


def check_bad_input(by_name):
    rows = by_name["5. bad input refused cleanly"]
    clean = sum(isinstance(r.get("status"), int) and 400 <= r["status"] < 500 and bool(r.get("error"))
                for r in rows)
    added = rows[0].get("decisions_added") if rows else None
    return f"{clean}/12 4xx, {added} decisions", clean == 12 and added == 0


SCENARIOS = [
    {
        "name": "1. known-human set",
        "target": "<= 1 of 20 labelled AI",
        "criterion": 1,
        "texts": HUMAN_TEXTS,
        "check": check_false_positives,
    },
    {
        "name": "2. known-AI set",
        "target": "mean AI - mean human >= 0.20",
        "criterion": 2,
        "texts": AI_TEXTS,
        "check": check_gap,
    },
    {
        "name": "3. label coverage (all 30)",
        "target": "3 of 3 labels live; 0 gaps in sweep",
        "criterion": 3,
        "texts": HUMAN_TEXTS + AI_TEXTS,
        "check": check_labels,
    },
    {
        "name": "4. appeal path",
        "target": "5/5 appeals logged + 3/3 unknown -> 404",
        "criterion": 4,
        "texts": HUMAN_TEXTS[:5],
        "appeal": True,
        "unknown_appeals": 3,
        "check": check_appeals,
    },
    {
        "name": "5. bad input refused cleanly",
        "target": "12/12 4xx with error; 0 decisions",
        "criterion": 5,
        # The twelve malformed requests criterion 5 names, in its order.
        "bodies": [
            {"_raw": "{this is not json", "_content_type": "application/json"},
            {"_raw": "text=hello&creator_id=x", "_content_type": "application/x-www-form-urlencoded"},
            {"_raw": json.dumps(["text", "creator_id"]), "_content_type": "application/json"},
            {"creator_id": "eval_bad_missing_text"},
            {"text": "", "creator_id": "eval_bad_empty"},
            {"text": "  \n\t  ", "creator_id": "eval_bad_whitespace"},
            {"text": 12345, "creator_id": "eval_bad_number"},
            {"text": _OK_TEXT},
            {"text": _OK_TEXT, "creator_id": ""},
            {"text": _OK_TEXT, "creator_id": ["x"]},
            {"text": "word " * 4001, "creator_id": "eval_bad_huge"},
            {"text": "Too short to judge.", "creator_id": "eval_bad_short"},
        ],
        "check": check_bad_input,
    },
]


def validate() -> list[str]:
    """
    Complain about anything malformed, before a long run rather than during.

    A "bodies" scenario is deliberately exempt from the empty check — an empty
    string is the whole point of a bad-input case, and refusing to run one
    would make that criterion untestable.
    """
    problems = []
    for i, scenario in enumerate(SCENARIOS, 1):
        if not scenario.get("name"):
            problems.append(f"scenario {i} has no name")

        texts = scenario.get("texts")
        bodies = scenario.get("bodies")

        if texts and bodies:
            problems.append(
                f"scenario {i} ('{scenario.get('name')}') has both texts and "
                f"bodies — pick one"
            )
            continue

        if bodies:
            for j, body in enumerate(bodies, 1):
                if not isinstance(body, dict):
                    problems.append(
                        f"scenario {i}, body {j} is not a dict — bodies are whole "
                        f"request bodies, like {{'text': '', 'creator_id': 'x'}}"
                    )
            continue

        if not texts:
            problems.append(f"scenario {i} has no texts and no bodies")
            continue

        for j, text in enumerate(texts, 1):
            if not str(text).strip():
                problems.append(
                    f"scenario {i}, text {j} is empty — if an empty submission is what "
                    f"you're testing, use 'bodies' instead of 'texts'"
                )
            elif str(text).startswith("REPLACE ME"):
                problems.append(
                    f"scenario {i} ('{scenario.get('name')}'), text {j} is still "
                    f"the placeholder"
                )
    return problems
